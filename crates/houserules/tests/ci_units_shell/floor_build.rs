//! The floor build of `floor-install: default-branch` in both units. The real `cargo` of this
//! host builds a small crate named `houserules` in a source of the default branch, while the
//! tree of the request holds the two files that could run a program of the request: a
//! `rust-toolchain.toml` with a `path` toolchain, and a `.cargo/config.toml` with a
//! `rustc-wrapper`. No planted program may run.
//!
//! rustup reads `rust-toolchain.toml` in the working directory and the folders above it, and
//! cargo reads `.cargo/config.toml` in the folders above the source of `--path`. The
//! `RUSTUP_TOOLCHAIN` variable outranks the toolchain file, so the toolchain half of a run needs
//! a host whose rustup picks a toolchain without it (a default toolchain). On another host the
//! run keeps the variable and shows the half that cargo's configuration gives.

use super::*;

use crate::ci_support::checkout_path;

/// The program of the crate that the tests build: it writes a valid route to the file after
/// `--json`, as `route --no-audit` does.
const TOY_MAIN: &str = "fn main() {\n\
    let arguments: Vec<String> = std::env::args().collect();\n\
    if let Some(index) = arguments.iter().position(|argument| argument == \"--json\") {\n\
        std::fs::write(&arguments[index + 1], \"{\\\"route\\\":\\\"owner-review\\\"}\\n\").unwrap();\n\
    }\n\
}\n";

/// A lock file for the crate, so that `cargo install --locked` needs no network.
const TOY_LOCK: &str = "# This file is automatically @generated by Cargo.\n\
    # It is not intended for manual editing.\n\
    version = 4\n\n\
    [[package]]\n\
    name = \"houserules\"\n\
    version = \"0.0.1\"\n";

/// A program that logs its name and arguments to the file `log`, then runs the rest of its
/// command line when `chain` is set.
fn logging_program(log: &Path, chain: bool) -> String {
    let tail = if chain { "exec \"$@\"\n" } else { "" };
    format!("#!/bin/sh\necho \"$0 $*\" >> \"{}\"\n{tail}", text(log))
}

/// Writes the executable `program` with the text `body`.
fn write_executable(program: &Path, body: &str) {
    fs::create_dir_all(program.parent().expect("a folder")).expect("create the folder");
    fs::write(program, body).expect("write the program");
    fs::set_permissions(program, fs::Permissions::from_mode(0o755)).expect("make it executable");
}

/// Writes the crate `crates/houserules` below `source`: a program that needs no dependency.
fn write_toy_crate(source: &Path) {
    let crate_dir = source.join("crates").join("houserules");
    fs::create_dir_all(crate_dir.join("src")).expect("create the crate");
    fs::write(
        crate_dir.join("Cargo.toml"),
        "[package]\nname = \"houserules\"\nversion = \"0.0.1\"\nedition = \"2021\"\n\n[workspace]\n",
    )
    .expect("write Cargo.toml");
    fs::write(crate_dir.join("Cargo.lock"), TOY_LOCK).expect("write Cargo.lock");
    fs::write(crate_dir.join("src").join("main.rs"), TOY_MAIN).expect("write main.rs");
}

/// Plants the two files of a request that could run a program of its own below `request`: a
/// `rust-toolchain.toml` that names a toolchain by path, and a `.cargo/config.toml` that names a
/// `rustc-wrapper`. Every planted program appends a line to `log`.
fn plant_request_programs(request: &Path, log: &Path) {
    let toolchain = request.join("planted-toolchain");
    write_executable(
        &toolchain.join("bin").join("cargo"),
        &logging_program(log, false),
    );
    write_executable(
        &toolchain.join("bin").join("rustc"),
        &logging_program(log, false),
    );
    fs::write(
        request.join("rust-toolchain.toml"),
        format!("[toolchain]\npath = \"{}\"\n", text(&toolchain)),
    )
    .expect("write rust-toolchain.toml");
    let wrapper = request.join("planted-wrapper");
    write_executable(&wrapper, &logging_program(log, true));
    fs::create_dir_all(request.join(".cargo")).expect("create .cargo");
    fs::write(
        request.join(".cargo").join("config.toml"),
        format!("[build]\nrustc-wrapper = \"{}\"\n", text(&wrapper)),
    )
    .expect("write config.toml");
}

/// `true` when the rustup of this host picks a toolchain with no `RUSTUP_TOOLCHAIN` in the
/// environment, so that a toolchain file of the request has a chance to win.
fn rustup_picks_a_toolchain_without_the_variable() -> bool {
    Command::new("rustup")
        .args(["show", "active-toolchain"])
        .env_remove("RUSTUP_TOOLCHAIN")
        .current_dir(std::env::temp_dir())
        .output()
        .is_ok_and(|output| output.status.success() && !output.stdout.is_empty())
}

/// The environment in which the real `cargo` of this host builds inside `sandbox`: the host's
/// `PATH` behind the stubs of the sandbox, the homes of cargo and rustup, no network, and the
/// `RUSTUP_TOOLCHAIN` of the host only when rustup picks no toolchain without it.
fn real_cargo_environment(sandbox: &Sandbox) -> Vec<(String, String)> {
    let host_path = std::env::var_os("PATH").unwrap_or_default();
    let path = std::env::join_paths(
        std::iter::once(sandbox.bin()).chain(std::env::split_paths(&host_path)),
    )
    .expect("join the PATH");
    let mut pairs = vec![
        ("PATH".to_string(), text(Path::new(&path))),
        ("CARGO_NET_OFFLINE".to_string(), "true".to_string()),
    ];
    for name in ["HOME", "CARGO_HOME", "RUSTUP_HOME"] {
        if let Ok(value) = std::env::var(name) {
            pairs.push((name.to_string(), value));
        }
    }
    if !rustup_picks_a_toolchain_without_the_variable()
        && let Ok(value) = std::env::var("RUSTUP_TOOLCHAIN")
    {
        pairs.push(("RUSTUP_TOOLCHAIN".to_string(), value));
    }
    pairs
}

/// `pairs` as the borrowed pairs that `env_of` takes.
fn borrowed(pairs: &[(String, String)]) -> Vec<(&str, &str)> {
    pairs
        .iter()
        .map(|(name, value)| (name.as_str(), value.as_str()))
        .collect()
}

/// What the planted programs logged, or an empty text.
fn planted_log(path: &Path) -> String {
    fs::read_to_string(path).unwrap_or_default()
}

/// Spec 10.1, design.md 242: the GitHub floor builds the default branch with no file of the
/// request in reach. The request goes where the unit checks it out, the default branch where
/// the unit's `HOUSERULES_DEFAULT_SRC` names it, and the install step runs as the runner runs it.
#[test]
fn the_github_floor_build_runs_no_program_of_the_request() {
    let unit = github();
    let sandbox = Sandbox::new();
    let workspace = sandbox.work();
    let request = checkout_path(&unit, "floor", "pull_request.head.sha")
        .map_or_else(|| workspace.clone(), |path| workspace.join(path));
    let source = unit
        .step_variable("floor", "Install houserules", "HOUSERULES_DEFAULT_SRC")
        .expect("the source of the default branch")
        .replace("${{ github.workspace }}", &text(&workspace));
    let log = sandbox.path().join("planted.log");
    write_toy_crate(Path::new(&source));
    plant_request_programs(&request, &log);
    let github_path = text(&sandbox.temp().join("github_path"));
    let mut pairs = real_cargo_environment(&sandbox);
    pairs.extend([
        (
            "HOUSERULES_SOURCE".to_string(),
            "default-branch".to_string(),
        ),
        ("HOUSERULES_VERSION".to_string(), String::new()),
        ("HOUSERULES_DEFAULT_SRC".to_string(), source.clone()),
        ("GITHUB_PATH".to_string(), github_path),
    ]);
    let output = sandbox.run_bash(
        &unit.step_script("floor", "Install houserules"),
        env_of(&unit, "floor", &borrowed(&pairs)),
    );
    assert_eq!(
        planted_log(&log),
        "",
        "a program of the request ran in the floor build"
    );
    assert_eq!(
        output.status.code(),
        Some(0),
        "{}{}",
        stdout(&output),
        stderr(&output)
    );
    assert!(
        sandbox
            .temp()
            .join("houserules-bin-build")
            .join("bin")
            .join("houserules")
            .is_file(),
        "the floor built the crate of the default branch"
    );
}

/// Spec 10.1, design.md 242: the GitLab floor script builds the default branch while the request
/// holds the planted files, and `route --no-audit` runs the binary that the build made.
#[test]
fn the_gitlab_floor_build_runs_no_program_of_the_request() {
    let unit = gitlab("root");
    let sandbox = Sandbox::new();
    let remote = sandbox.path().join("remote").join("widgets.git");
    let repository = sandbox.work();
    let (first, _) = repository_with_origin(&repository, &remote);
    write_toy_crate(&repository);
    git(&repository, &["add", "."]);
    git(&repository, &["commit", "-q", "-m", "crate"]);
    git(
        &repository,
        &["push", "-q", "origin", "HEAD:refs/heads/main"],
    );
    let log = sandbox.path().join("planted.log");
    plant_request_programs(&repository, &log);
    git(&repository, &["add", "-f", "."]);
    git(&repository, &["commit", "-q", "-m", "request"]);
    let head = git(&repository, &["rev-parse", "HEAD"]).trim().to_string();
    let project = text(&repository);
    let mut pairs = real_cargo_environment(&sandbox);
    pairs.extend([
        ("HOUSERULES_DIR".to_string(), ".".to_string()),
        (
            "HOUSERULES_SOURCE".to_string(),
            "default-branch".to_string(),
        ),
        ("CI_DEFAULT_BRANCH".to_string(), "main".to_string()),
        ("CI_PROJECT_DIR".to_string(), project),
        ("CI_MERGE_REQUEST_DIFF_BASE_SHA".to_string(), first),
        ("CI_MERGE_REQUEST_SOURCE_BRANCH_SHA".to_string(), head),
        (
            "CI_COMMIT_SHA".to_string(),
            "cccccccccccccccccccccccccccccccccccccccc".to_string(),
        ),
    ]);
    let output = sandbox.run_sh(
        &unit.job_script("floor"),
        env_of(&unit, "floor", &borrowed(&pairs)),
    );
    assert_eq!(
        planted_log(&log),
        "",
        "a program of the request ran in the floor build"
    );
    assert_eq!(
        output.status.code(),
        Some(0),
        "{}{}",
        stdout(&output),
        stderr(&output)
    );
    assert_eq!(
        fs::read_to_string(sandbox.work().join("floor.env")).expect("the dotenv report"),
        "HOUSERULES_FLOOR_ROUTE=owner-review\n",
        "the binary that the build made computed the floor"
    );
}

/// A `rustup` that answers `show active-toolchain` with `$STUB_ACTIVE` and the exit status
/// `$STUB_ACTIVE_EXIT`, and logs its working directory and arguments.
const STUB_RUSTUP: &str = "#!/bin/sh\n\
    echo \"$PWD $*\" >> \"$STUB_DIR/rustup.log\"\n\
    if [ \"$1 $2\" = 'show active-toolchain' ]; then\n\
      [ -z \"${STUB_ACTIVE-}\" ] || echo \"$STUB_ACTIVE\"\n\
      exit \"${STUB_ACTIVE_EXIT:-0}\"\n\
    fi\n\
    exit 2\n";

/// A `cargo` that logs its working directory, the `RUSTUP_TOOLCHAIN` it sees, and its
/// arguments, then writes a `houserules` into the folder after `--root`.
const STUB_CARGO: &str = "#!/bin/sh\n\
    echo \"$PWD|${RUSTUP_TOOLCHAIN-unset}|$*\" >> \"$STUB_DIR/cargo.log\"\n\
    root=\n\
    while [ $# -gt 0 ]; do case $1 in --root) root=$2; shift 2;; *) shift;; esac; done\n\
    mkdir -p \"$root/bin\"\n\
    printf '#!/bin/sh\\necho houserules 1.4.0\\n' > \"$root/bin/houserules\"\n\
    chmod +x \"$root/bin/houserules\"\n";

/// Design.md 242: the build runs `cargo install` inside the source of the default branch, with
/// the toolchain pinned to the one that rustup picks there. The pin outranks any toolchain file
/// (rustup's order: the `RUSTUP_TOOLCHAIN` variable comes before a `rust-toolchain.toml`), so a
/// file of the request cannot select the toolchain even when the working directory moves. A
/// rustup that cannot answer sets no pin, and `cargo` still runs.
#[test]
fn the_floor_build_pins_the_toolchain_that_rustup_picks_in_the_source() {
    for (active, exit, expected) in [
        (
            "1.98.1-x86_64-unknown-linux-gnu (overridden by '/trusted/rust-toolchain.toml')",
            "0",
            "1.98.1-x86_64-unknown-linux-gnu",
        ),
        (
            "stable-x86_64-unknown-linux-gnu (default)",
            "0",
            "stable-x86_64-unknown-linux-gnu",
        ),
        ("", "1", "unset"),
    ] {
        let unit = github();
        let sandbox = Sandbox::new();
        sandbox.install_program("rustup", STUB_RUSTUP);
        sandbox.install_program("cargo", STUB_CARGO);
        let source = sandbox.path().join("default-branch");
        fs::create_dir_all(source.join("crates").join("houserules")).expect("create the crate");
        fs::write(
            source.join("crates").join("houserules").join("Cargo.toml"),
            "",
        )
        .expect("write Cargo.toml");
        let source_text = text(&source);
        let github_path = text(&sandbox.temp().join("github_path"));
        let output = sandbox.run_bash(
            &unit.step_script("floor", "Install houserules"),
            env_of(
                &unit,
                "floor",
                &[
                    ("HOUSERULES_SOURCE", "default-branch"),
                    ("HOUSERULES_VERSION", ""),
                    ("HOUSERULES_DEFAULT_SRC", source_text.as_str()),
                    ("GITHUB_PATH", github_path.as_str()),
                    ("STUB_ACTIVE", active),
                    ("STUB_ACTIVE_EXIT", exit),
                ],
            ),
        );
        assert_eq!(
            output.status.code(),
            Some(0),
            "{active:?}: {}{}",
            stdout(&output),
            stderr(&output)
        );
        let cargo = fs::read_to_string(sandbox.stub_dir().join("cargo.log")).expect("cargo log");
        let line = cargo.lines().next().expect("a cargo call");
        let mut parts = line.splitn(3, '|');
        assert_eq!(
            parts.next(),
            Some(source_text.as_str()),
            "{active:?}: cargo works inside the source of the default branch"
        );
        assert_eq!(
            parts.next(),
            Some(expected),
            "{active:?}: the pinned toolchain"
        );
        let rustup = fs::read_to_string(sandbox.stub_dir().join("rustup.log")).expect("rustup log");
        assert!(
            rustup.starts_with(&format!("{source_text} show active-toolchain")),
            "{active:?}: rustup answers inside the source: {rustup}"
        );
    }
}

/// Design.md 242: the GitLab floor script refuses a source of the default branch that lies in the
/// checkout of the request (a `TMPDIR` below the project folder), before it builds anything.
#[test]
fn the_gitlab_floor_refuses_a_source_inside_the_request_checkout() {
    let unit = gitlab("root");
    let sandbox = Sandbox::new();
    let remote = sandbox.path().join("remote").join("widgets.git");
    let repository = sandbox.work();
    let (first, second) = repository_with_origin(&repository, &remote);
    sandbox.install_program("cargo", STUB_CARGO);
    let inside = repository.join("scratch");
    fs::create_dir_all(&inside).expect("create the scratch folder");
    let project = text(&repository);
    let scratch = text(&inside);
    let env = env_of(
        &unit,
        "floor",
        &[
            ("HOUSERULES_DIR", "."),
            ("HOUSERULES_SOURCE", "default-branch"),
            ("CI_DEFAULT_BRANCH", "main"),
            ("CI_PROJECT_DIR", project.as_str()),
            ("TMPDIR", scratch.as_str()),
            ("CI_MERGE_REQUEST_DIFF_BASE_SHA", first.as_str()),
            ("CI_MERGE_REQUEST_SOURCE_BRANCH_SHA", second.as_str()),
            ("CI_COMMIT_SHA", "cccccccccccccccccccccccccccccccccccccccc"),
        ],
    );
    let output = sandbox.run_sh(&unit.job_script("floor"), env);
    assert_eq!(output.status.code(), Some(1), "{}", stderr(&output));
    assert_eq!(
        stdout(&output),
        "houserules: the source of the default branch is inside the checkout of the request\n"
    );
    assert!(
        !sandbox.stub_dir().join("cargo.log").exists(),
        "nothing was built"
    );
}
